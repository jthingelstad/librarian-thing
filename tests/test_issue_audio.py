def _load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


upload = _load("test_audio_upload_corpus", DEPLOY / "upload_corpus.py")
push_graph = _load("test_audio_push_graph", DEPLOY / "push_graph.py")

AUDIO_URL = "https://files.thingelstad.com/weekly-thing/351/weekly-thing-351-82e8257b.mp3"
CHAPTER_ONLY_TITLE = "Chapter Marker Zebra"
THINGY_QUESTION = "What has Jamie taken from Ethan Mollick's writing on AI?"

