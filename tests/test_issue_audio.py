def test_audio_rides_the_issue_record_never_chunks_or_embed_input(tmp_path):
    plain = _corpus(tmp_path / "plain")
    corpus = _corpus(tmp_path / "with-audio")

    assert audio.annotate_issue_audio(corpus, _site(tmp_path)) == 1
    assert _issue(corpus, 351)["audio"]["url"] == AUDIO_URL

    for chunk in corpus["chunks"]:
        assert "audio" not in chunk
        for text in (chunk.get("text") or "", _embed_input(chunk)):
            assert AUDIO_URL not in text
            assert CHAPTER_ONLY_TITLE not in text
    # Chunk ids and embed inputs are byte-identical: the embedding cache stays warm.
    assert [(c["id"], _embed_input(c)) for c in corpus["chunks"]] == [
        (c["id"], _embed_input(c)) for c in plain["chunks"]
    ]


