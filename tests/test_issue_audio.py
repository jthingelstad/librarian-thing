"""Audio pointers on Weekly Thing issue records, and the graph the site gets.

Plan 2026-09-29 Phase 3 items 6 and 7. The audio record lives only in the
weekly site's archive page frontmatter; the build stamps issue records with
`audio: {url, duration_seconds, chapters: [{start, title}]}` and never lets it
near chunk text or the embedding input. The site's graph is the one built
from the embedded corpus, so its `similar_issues` are real.
"""

