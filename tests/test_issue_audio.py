def _site(root: Path) -> Path:
    site = root / "apps" / "site" / "archive"
    site.mkdir(parents=True)
    (site / "351.md").write_text(WITH_AUDIO, encoding="utf-8")
    (site / "350.md").write_text(WITHOUT_AUDIO, encoding="utf-8")
    (site / "349.md").write_text(MALFORMED, encoding="utf-8")
    (site / "348.md").write_text("No frontmatter at all.\n", encoding="utf-8")
    return site


def _archive(root: Path) -> Path:
    archive = root / "issues"
    for number, topic in ((351, "attention"), (350, "agents"), (349, "rails"), (348, "cats")):
        (archive / str(number)).mkdir(parents=True)
        (archive / str(number) / "archive.md").write_text(
            f"---\nnumber: {number}\nsubject: Weekly Thing {number}\n"
            "publish_date: '2026-09-26T12:00:00Z'\n---\n"
            f"Intro about {topic}.\n\n## Notable\n\nA long thought about {topic}.\n",
            encoding="utf-8",
        )
    return archive


def _empty_site_dir(root: Path) -> Path:
    site = root / "site"
    (site / "_data").mkdir(parents=True)
    return site


def _corpus(root: Path) -> dict:
    return build_corpus(
        _archive(root),
        include_issue_bodies=True,
        site_dir=_empty_site_dir(root),
        faq_path=root / "missing-faq.json",
    )


def _issue(corpus: dict, number: int) -> dict:
    return next(issue for issue in corpus["issues"] if str(issue["number"]) == str(number))


def test_issue_with_audio_gets_the_pointer_and_chapters_trimmed(tmp_path):
    corpus = {"issues": [{"number": 351}]}

