# --- Item 6: the site's graph carries real similar_issues ---


def _fake_embed(corpus, *_args, **_kwargs):
    for index, chunk in enumerate(corpus["chunks"]):
        chunk["embedding"] = [1.0, float(index % 3), 0.5]


def test_uploaded_graph_is_built_from_the_embedded_corpus(tmp_path):
    uploaded: dict[str, dict] = {}

    def capture(_bucket, key, path):
        uploaded[key] = json.loads(Path(path).read_text(encoding="utf-8"))

    argv = ["upload_corpus.py", "--bucket", "b", "--key", "artifacts/corpus.json"]
    with (
        mock.patch.object(upload, "ARCHIVE_DIR", _archive(tmp_path)),
        mock.patch.object(upload, "MEDIA_DESCRIPTIONS_PATH", tmp_path / "none.json"),
        mock.patch.dict("os.environ", {audio.SITE_ARCHIVE_ENV: str(tmp_path / "absent")}),
        mock.patch.object(upload, "load_dotenv"),
        mock.patch.object(upload, "fetch_existing_corpus", return_value=None),
        mock.patch.object(upload, "add_bedrock_embeddings", side_effect=_fake_embed),
        mock.patch.object(upload, "upload_json_gzip", side_effect=capture),
        mock.patch.object(sys, "argv", argv),
    ):
        assert upload.main() == 0

    graph = uploaded["artifacts/graph.json"]
    assert set(graph["issues"]) == {"348", "349", "350", "351"}
    assert all(issue["similar_issues"] for issue in graph["issues"].values())
    assert "None" not in graph["issues"]


GRAPH = {
    "version": 1,
    "issues": {
        "1": {"entities": [], "tropes": [], "similar_issues": [{"number": "2", "score": 0.9}]},
        "2": {"entities": [], "tropes": [], "similar_issues": [{"number": "1", "score": 0.9}]},
    },
}


class _S3:
    def __init__(self, body: bytes):
        self.body = body
        self.calls: list[tuple[str, str]] = []

    def get_object(self, Bucket, Key):
        self.calls.append((Bucket, Key))
        return {"Body": mock.Mock(read=mock.Mock(return_value=self.body))}


def _run_push(argv: list[str], s3: _S3, **patches):
    with (
        mock.patch.object(push_graph.boto3, "client", return_value=s3),
        mock.patch.object(sys, "argv", ["push_graph.py", *argv]),
        mock.patch.multiple(push_graph.github_repo, **patches),
    ):
        return push_graph.main()


def test_handoff_pushes_the_s3_graph_not_the_local_file(tmp_path):
    s3 = _S3(gzip.compress(json.dumps(GRAPH).encode()))
    # The pre-embedding graph a local build leaves behind: no similar_issues.
    stale_local = tmp_path / "data" / "librarian" / "graph.json"
    stale_local.parent.mkdir(parents=True)
    stale_local.write_text(json.dumps({"issues": {"1": {"similar_issues": []}}}))
    put_tree = mock.Mock(return_value="abc1234def")

    with (
        mock.patch.object(push_graph, "REPO_ROOT", tmp_path),
        mock.patch.object(push_graph, "GRAPH", stale_local),
    ):
        assert _run_push(["--from-s3", "--push"], s3, put_tree=put_tree) == 0

    assert s3.calls == [("weekly-thing-librarian", "artifacts/graph.json")]
    (files, message), kwargs = put_tree.call_args
    [(path, content)] = files
    assert path == "data/librarian/graph.json"
    assert json.loads(content) == GRAPH
    # Written the way pipeline/graph/build.py writes it, so site diffs stay readable.
    assert content == (json.dumps(GRAPH, ensure_ascii=False, indent=2) + "\n").encode()


def test_handoff_dry_run_from_s3_reads_plain_json_too(capsys):
    s3 = _S3(json.dumps(GRAPH).encode())
    get = mock.Mock(return_value={"tree": []})

    assert _run_push(["--from-s3"], s3, _get=get, _repo=mock.Mock(return_value="o/r")) == 0

    out = capsys.readouterr().out
    assert "similar_issues on 2 of 2 issues" in out
    assert "graph.json added" in out


def test_handoff_pushes_nothing_when_the_s3_graph_cannot_be_read():
    s3 = _S3(b"not json")
    put_tree = mock.Mock()

    with pytest.raises(json.JSONDecodeError):
        _run_push(["--from-s3", "--push"], s3, put_tree=put_tree)
    put_tree.assert_not_called()
