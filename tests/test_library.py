class ConditionalUploadTests(unittest.TestCase):
    def setUp(self):
        self.client = boto3.client("s3", region_name="us-east-1")
        self.stub = Stubber(self.client)
        self._tmp = tempfile.TemporaryDirectory()
        self.db = Path(self._tmp.name) / "library.db"
        self.db.write_bytes(b"SQLite format 3\x00")

    def tearDown(self):
        self._tmp.cleanup()

    def _expect_put(self, condition: dict, *, error: str | None = None):
        params = {
            "Bucket": store.DEFAULT_BUCKET,
            "Key": store.KEY,
            "Body": ANY,
            "ContentType": "application/vnd.sqlite3",
            **condition,
        }
        if error:
            self.stub.add_client_error(
                "put_object", service_error_code=error, http_status_code=412, expected_params=params
            )
        else:
            self.stub.add_response("put_object", {"ETag": '"new"'}, params)

    def test_replaces_only_the_copy_it_downloaded(self):
        self._expect_put({"IfMatch": '"old"'})
        with self.stub:
            self.assertEqual(store.upload(self.db, '"old"', client=self.client), '"new"')

    def test_the_first_copy_must_not_overwrite_one(self):
        self._expect_put({"IfNoneMatch": "*"})
        with self.stub:
            store.upload(self.db, None, client=self.client)

    def test_a_second_writer_gets_a_conflict(self):
        self._expect_put({"IfMatch": '"old"'}, error="PreconditionFailed")
        with self.stub, self.assertRaises(store.LibraryConflict):
            store.upload(self.db, '"old"', client=self.client)

    def test_download_writes_the_copy_and_returns_its_etag(self):
        data = b"SQLite format 3\x00" + bytes(3 << 20)
        self.stub.add_response(
            "get_object",
            {"Body": StreamingBody(io.BytesIO(data), len(data)), "ETag": '"cur"'},
            {"Bucket": store.DEFAULT_BUCKET, "Key": store.KEY},
        )
        dest = Path(self._tmp.name) / "copy" / "library.db"
        with self.stub:
            self.assertEqual(store.download(dest, client=self.client), '"cur"')
        self.assertEqual(dest.read_bytes(), data)
        self.assertFalse(dest.with_name("library.db.part").exists())

    def test_download_with_no_library_yet_leaves_the_file_alone(self):
        self.stub.add_client_error(
            "get_object", service_error_code="NoSuchKey", http_status_code=404
        )
        with self.stub:
            self.assertIsNone(store.download(self.db, client=self.client))
        self.assertEqual(self.db.read_bytes(), b"SQLite format 3\x00")


def _load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


