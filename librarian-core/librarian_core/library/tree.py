"""The data tree as a working copy of the library: export it, work on it,
absorb what changed.

The tree keeps the layout the ingesters and the corpus build have always read
(``blog/``, ``podcast/``, ``things/``, ``site/``, ``reference/``,
``reference-unpublished/``, ``librarian/``), plus
``weekly/archive/<n>.md``, weekly.thingelstad.com's archive pages exactly as
WT Builder published them. ``issues/<n>/archive.md``, the issue text the
corpus build reads, is derived from those pages on export and never absorbed:
weekly is the authority for issues (Jamie, 2026-10-01).
"""

from __future__ import annotations

import json
import re
import shutil
import sqlite3
from pathlib import Path

from librarian_core.library.db import LibraryError, meta_get, now, sha256
from librarian_core.library.readers import CORPUS_READERS, readers_export, readers_fingerprint

# Path prefixes the library owns in the tree, and the source each came from.
# Everything else in the tree (built corpora, the graph, derived issues) is
# output and never absorbed.
MANAGED: tuple[tuple[str, str], ...] = (
    ("blog/", "micro.blog"),
    ("weekly/archive/", "weekly"),
    ("site/", "weekly"),
    ("podcast/", "another"),
    ("things/", "xyz"),
    # reference-documents/ on main, by pipeline/reference/import_reference.py.
    ("reference/", "reference"),
    # Reference documents kept out of the public repository: placed here by
    # hand (absorb, then upload), never by a pull, so no round removes them.
    ("reference-unpublished/", "reference-unpublished"),
    ("librarian/media-descriptions.json", "librarian"),
    ("librarian/blog-abstracts.json", "librarian"),
)
DERIVED_DIR = "issues"
# The reader numbers as the corpus build reads them: written from the
# library's reader tables on every export, never absorbed.
READERS_FILE = "librarian/readers.json"
MARKER = ".library.json"
# Hand-written notes that sat beside the content in git; not content.
_IGNORED_NAMES = {"README.md", ".DS_Store", MARKER}

# An absorb that would remove more than this share of one origin's files
# (and more than a handful) is a broken pull or a partial tree, not the
# source deleting things; it refuses unless told otherwise.
REMOVAL_FLOOR = 5
REMOVAL_SHARE = 0.10

# weekly's page front matter adds these for the website (layout, routing,
# the audio player) to the issue's own fields; the issue text drops them.
WEB_ONLY_KEYS = frozenset(
    {
        "layout",
        "permalink",
        "tags",
        "templateEngineOverride",
        "audio_url",
        "audio_duration_seconds",
        "audio_byte_size",
        "audio_voice",
        "audio_chapters_url",
        "audio_transcript_url",
        "audio_chapters",
    }
)
_GENERATED_NOTICE_RE = re.compile(r"<!-- Generated by WT Builder[^\n]*-->\n")

# What each corpus is built from, as tree prefixes. Its fingerprint is a hash
# over those files' hashes: the build records the one it was built from on
# the uploaded corpus, and a library whose fingerprint differs is newer than
# the corpus serving. The Weekly Thing and blog builds read each other (a
# Journal copy's post, a post's issues) and the episodes (link lookups). The
# reference build reads the issues only for what the site pages and the FAQ
# say about the archive (how many, over how many years, the newest), and the
# FAQ itself from git (apps/librarian/lambda/shared/faq.json), so a change
# there is deploy.yml's to notice.
CORPUS_INPUTS: dict[str, tuple[str, ...]] = {
    "corpus": (
        "weekly/archive/",
        "blog/",
        "podcast/",
        "librarian/media-descriptions.json",
    ),
    "blog_corpus": (
        "blog/",
        "weekly/archive/",
        "podcast/",
        "librarian/media-descriptions.json",
        "librarian/blog-abstracts.json",
    ),
    "podcast_corpus": ("podcast/",),
    "reference_corpus": (
        "weekly/archive/",
        "site/",
        "things/",
        "blog/pages/",
        "reference/",
        "reference-unpublished/",
    ),
}


def origin_of(path: str) -> str | None:
    """The source a tree path belongs to, or None when the library does not
    keep it."""
    if Path(path).name in _IGNORED_NAMES:
        return None
    for prefix, origin in MANAGED:
        if prefix.endswith("/"):
            if path.startswith(prefix):
                if prefix == "weekly/archive/" and not path.endswith(".md"):
                    return None
                return origin
        elif path == prefix:
            return origin
    return None


def issue_from_weekly_page(text: str) -> str:
    """The issue text (``issues/<n>/archive.md``) from weekly's archive page:
    the same front matter less the website-only keys, and the body less WT
    Builder's generated-file notice."""
    if not text.startswith("---\n"):
        raise LibraryError("weekly archive page has no front matter")
    end = text.find("\n---\n", 4)
    if end < 0:
        raise LibraryError("weekly archive page front matter is not closed")
    kept: list[str] = []
    skipping = False
    for line in text[4:end].split("\n"):
        # A top-level key starts at column 0; indented lines and list items
        # belong to the key above them.
        if line and not line[0].isspace() and not line.startswith("- "):
            skipping = line.split(":", 1)[0] in WEB_ONLY_KEYS
        if not skipping:
            kept.append(line)
    body = text[end + 5 :]
    if _GENERATED_NOTICE_RE.match(body):
        body = body[_GENERATED_NOTICE_RE.match(body).end() :]
    return "---\n" + "\n".join(kept) + "\n---\n" + body


def fingerprints(conn: sqlite3.Connection) -> dict[str, str]:
    """Each corpus's fingerprint: what the library holds of its inputs,
    reader numbers included (a day's counts make the corpus stale)."""
    rows = conn.execute("SELECT path, sha256 FROM files ORDER BY path").fetchall()
    readers = readers_export(conn)
    out = {}
    for corpus, prefixes in CORPUS_INPUTS.items():
        lines = [f"{path} {digest}" for path, digest in rows if path.startswith(prefixes)]
        # The reference corpus carries no reader numbers: a site page's, a
        # thing's and a page's ride the corpora whose tools show them.
        if corpus in CORPUS_READERS and (readers["sources"] or readers["sites"]):
            lines.append(f"{READERS_FILE} {readers_fingerprint(readers, corpus)}")
        out[corpus] = sha256("\n".join(lines))[:32]
    return out


def write_readers(conn: sqlite3.Connection, tree: str | Path) -> int:
    """Write the reader numbers the corpus build reads. Returns how many
    sources carry numbers."""
    export = readers_export(conn)
    path = Path(tree) / READERS_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(export, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    return len(export["sources"])


def read_marker(tree: str | Path) -> dict | None:
    """The export marker of a tree, or None when no export wrote it."""
    marker = Path(tree) / MARKER
    if not marker.exists():
        return None
    return json.loads(marker.read_text(encoding="utf-8"))


def _write_marker(conn: sqlite3.Connection, tree: Path, **values) -> None:
    marker = {
        **(read_marker(tree) or {}),
        "library_id": meta_get(conn, "library_id"),
        **values,
        "fingerprints": fingerprints(conn),
    }
    (tree / MARKER).write_text(json.dumps(marker, indent=2) + "\n", encoding="utf-8")


def _derive_issue(tree: Path, page_path: str, content: str | None) -> None:
    """Write (or, for a page gone, remove) the issue text derived from one of
    weekly's archive pages."""
    issue = tree / DERIVED_DIR / Path(page_path).stem / "archive.md"
    if content is None:
        shutil.rmtree(issue.parent, ignore_errors=True)
        return
    issue.parent.mkdir(parents=True, exist_ok=True)
    issue.write_bytes(issue_from_weekly_page(content).encode("utf-8"))


def _managed_files(tree: Path) -> dict[str, Path]:
    found: dict[str, Path] = {}
    for prefix, _origin in MANAGED:
        base = tree / prefix
        if prefix.endswith("/"):
            if not base.is_dir():
                continue
            candidates = (p for p in base.rglob("*") if p.is_file())
        else:
            candidates = [base] if base.is_file() else []
        for path in candidates:
            rel = path.relative_to(tree).as_posix()
            if origin_of(rel):
                found[rel] = path
    return found


def export_tree(conn: sqlite3.Connection, tree: str | Path, *, force: bool = False) -> int:
    """Write every file in the library to ``tree`` and derive the issue texts.
    The managed paths and ``issues/`` are cleared first, so the tree matches
    the library exactly; build outputs elsewhere in the tree are left alone.
    Refuses a non-empty tree that no export wrote, unless ``force``."""
    tree = Path(tree)
    if tree.exists() and any(tree.iterdir()) and not (tree / MARKER).exists() and not force:
        raise LibraryError(
            f"{tree} holds files the library did not write; export into an empty "
            "directory or an earlier export (or pass force)"
        )
    tree.mkdir(parents=True, exist_ok=True)
    for prefix, _origin in MANAGED:
        target = tree / prefix
        if prefix.endswith("/"):
            shutil.rmtree(target, ignore_errors=True)
        else:
            target.unlink(missing_ok=True)
    shutil.rmtree(tree / DERIVED_DIR, ignore_errors=True)

    written = 0
    for row in conn.execute("SELECT path, content FROM files ORDER BY path"):
        path = tree / row["path"]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(row["content"].encode("utf-8"))
        written += 1
        if row["path"].startswith("weekly/archive/"):
            _derive_issue(tree, row["path"], row["content"])
    write_readers(conn, tree)
    (tree / MARKER).unlink(missing_ok=True)
    _write_marker(conn, tree, exported_at=now(), files=written)
    return written


def absorb_tree(
    conn: sqlite3.Connection,
    tree: str | Path,
    *,
    origins: set[str] | None = None,
    allow_removals: bool = False,
    seed: bool = False,
    note: str | None = None,
) -> dict[str, dict[str, list[str]]]:
    """Take the tree's managed files back into the library: add new ones,
    replace changed ones, remove the ones gone from the tree. Only the
    ``origins`` given are compared (all by default). Returns, per origin, the
    paths added, changed and removed.

    The tree must be an export of this library (its marker names the same
    library), unless ``seed`` (the first import into an empty library).
    Refuses, changing nothing, when one origin would lose more than a tenth
    of its files, unless ``allow_removals``. Afterwards the issue texts of
    weekly pages that changed are derived again and the marker carries the
    library's new fingerprints, so the tree reads as a fresh export."""
    tree = Path(tree)
    if not seed:
        marker = tree / MARKER
        if not marker.exists():
            raise LibraryError(f"{tree} was not exported from a library; refusing to absorb it")
        exported_from = json.loads(marker.read_text(encoding="utf-8")).get("library_id")
        if exported_from != meta_get(conn, "library_id"):
            raise LibraryError(f"{tree} was exported from another library; refusing to absorb it")

    known: dict[str, tuple[str, str]] = {
        row["path"]: (row["origin"], row["sha256"])
        for row in conn.execute("SELECT path, origin, sha256 FROM files")
    }
    in_scope = (lambda origin: True) if origins is None else (lambda origin: origin in origins)

    changes: dict[str, dict[str, list[str]]] = {}
    contents: dict[str, tuple[str, str, str]] = {}
    present = _managed_files(tree)
    for rel, path in sorted(present.items()):
        origin = origin_of(rel)
        if origin is None or not in_scope(origin):
            continue
        try:
            text = path.read_bytes().decode("utf-8")
        except UnicodeDecodeError as exc:
            raise LibraryError(f"{rel} is not UTF-8 text") from exc
        digest = sha256(text)
        bucket = changes.setdefault(origin, {"added": [], "changed": [], "removed": []})
        if rel not in known:
            bucket["added"].append(rel)
        elif known[rel][1] != digest:
            bucket["changed"].append(rel)
        else:
            continue
        contents[rel] = (origin, text, digest)
    for rel, (origin, _digest) in sorted(known.items()):
        if in_scope(origin) and rel not in present:
            changes.setdefault(origin, {"added": [], "changed": [], "removed": []})[
                "removed"
            ].append(rel)

    if not allow_removals:
        for origin, bucket in changes.items():
            held = sum(1 for o, _ in known.values() if o == origin)
            gone = len(bucket["removed"])
            if gone > REMOVAL_FLOOR and gone > REMOVAL_SHARE * held:
                raise LibraryError(
                    f"absorbing would remove {gone} of {held} {origin} files; "
                    "a pull that short is broken, not a deletion. Nothing changed."
                )

    stamp = now()
    with conn:
        for rel, (origin, text, digest) in contents.items():
            conn.execute(
                "INSERT INTO files (path, origin, content, sha256, pulled_at) VALUES (?, ?, ?, ?, ?) "
                "ON CONFLICT (path) DO UPDATE SET origin = excluded.origin, "
                "content = excluded.content, sha256 = excluded.sha256, pulled_at = excluded.pulled_at",
                (rel, origin, text, digest, stamp),
            )
        for bucket in changes.values():
            conn.executemany("DELETE FROM files WHERE path = ?", [(p,) for p in bucket["removed"]])
        for origin, bucket in sorted(changes.items()):
            if bucket["added"] or bucket["changed"] or bucket["removed"]:
                conn.execute(
                    "INSERT INTO pulls (at, origin, added, changed, removed, note) "
                    "VALUES (?, ?, ?, ?, ?, ?)",
                    (
                        stamp,
                        origin,
                        len(bucket["added"]),
                        len(bucket["changed"]),
                        len(bucket["removed"]),
                        note,
                    ),
                )
    if not seed:
        weekly = changes.get("weekly", {})
        for rel in [*weekly.get("added", []), *weekly.get("changed", [])]:
            if rel.startswith("weekly/archive/"):
                _derive_issue(tree, rel, contents[rel][1])
        for rel in weekly.get("removed", []):
            if rel.startswith("weekly/archive/"):
                _derive_issue(tree, rel, None)
        _write_marker(conn, tree, absorbed_at=stamp)
    return changes
